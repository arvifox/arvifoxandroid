#!/bin/bash

# Проверяем, передан ли путь к директории
if [ -z "$1" ]; then
    echo "Ошибка: не указан путь к директории"
    echo "Использование: ./script.sh /путь/к/директории"
    exit 1
fi

# Проверяем, существует ли указанная директория
if [ ! -d "$1" ]; then
    echo "Ошибка: указанная директория не существует"
    exit 1
fi

# Удаляем все директории с именем build рекурсивно
echo "Начинаем удаление директорий build в $1"
find "$1" -type d -name "build" -exec rm -rf {} \;

echo "Удаление завершено"
